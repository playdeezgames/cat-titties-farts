#!/usr/bin/env python3
"""Cuts the tiles this game uses out of the Urizen 1-bit tileset (vurmux, CC0) into odin/game/tile_data.odin.

The sheet has 12 px tiles with a 1 px gap: tile (col, row) starts at (13*col+1, 13*row+1). Each tile has one colour
on black, so a glyph is just a mask (any lit pixel is set) and the game picks the hue. Each row is a u16, bit x = column x.
"""
import os
from PIL import Image

root = os.path.join(os.path.dirname(__file__), "..")
sheet = Image.open(os.path.join(root, "assets", "tiles", "urizen_onebit_tileset__v2d0.png")).convert("RGB")

# name -> (col, row) on the sheet. Order here is the order of the Odin enum.
TILES = [
    ("Wall", (0, 3)),     # red brick
    ("Bed", (1, 36)),
    ("Chair", (15, 36)),
    ("Table", (15, 35)),
    ("Sofa", (21, 36)),
    ("Shelf", (2, 36)),
    ("Plant", (16, 9)),   # small shrub
    ("Cat", (1, 14)),
    ("Person", (104, 0)), # plain white person
]

lines = [
    "// Generated by tools/gen_tiles.py from assets/tiles/urizen_onebit_tileset__v2d0.png (Urizen by vurmux, CC0). Do not edit.",
    "package game",
    "",
    "TILE_SIZE :: 12",
    "",
    "Tile :: enum {",
]
for name, _ in TILES:
    lines.append(f"\t{name},")
lines += ["}", "", "TILE_GLYPHS := [Tile][TILE_SIZE]u16 {"]
for name, (c, r) in TILES:
    x0, y0 = 13 * c + 1, 13 * r + 1
    rows = []
    for y in range(12):
        bits = 0
        for x in range(12):
            if max(sheet.getpixel((x0 + x, y0 + y))) > 0:
                bits |= 1 << x
        rows.append(bits)
    assert any(rows), f"{name} at {(c, r)} is empty"
    lines.append(f"\t.{name} = {{" + ", ".join(str(v) for v in rows) + "},")
lines.append("}")
with open(os.path.join(root, "odin", "game", "tile_data.odin"), "w") as f:
    f.write("\n".join(lines) + "\n")
